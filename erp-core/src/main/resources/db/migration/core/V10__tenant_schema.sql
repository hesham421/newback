-- 6. PLATFORM_TENANT_MANAGE — registry rows (global) + grants to the PLATFORM tenant's SYS_ADMIN.
--    The code is the step-05 plan's literal (like CU's CONFIG_* codes, not PERM_<PAGE>_<ACTION>).
--    RULE-SEC-007 (MenuService.effectiveAuthorityCodes): a screen's non-VIEW actions are effective
--    only together with that screen's VIEW (gateway) action, so the screen also carries
