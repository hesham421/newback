INSERT INTO SEC_SCREEN_REG (SCREEN_REG_PK, PAGE_CODE, MODULE_ID, NAME_AR, NAME_EN, IS_ACTIVE_FL, CREATED_BY, CREATED_AT)
SELECT nextval('SEQ_SEC_SCREEN_REG'), 'PLATFORM_TENANTS', m.MODULE_REG_PK, 'المستأجرون', 'Tenants', TRUE, 'SYSTEM', CURRENT_TIMESTAMP
FROM SEC_MODULE_REG m WHERE m.CODE = 'PLATFORM';

INSERT INTO SEC_ACTION_REG (ACTION_REG_PK, PERMISSION_CODE, SCREEN_ID, ACTION_CODE, NAME_AR, NAME_EN, IS_ACTIVE_FL, CREATED_BY, CREATED_AT)
SELECT nextval('SEQ_SEC_ACTION_REG'), v.permission_code, s.SCREEN_REG_PK, v.action_code,
       s.NAME_AR || ' - ' || v.action_ar, s.NAME_EN || ' - ' || v.action_code, TRUE, 'SYSTEM', CURRENT_TIMESTAMP
FROM (VALUES
    (1, 'VIEW',   'عرض',  'PERM_PLATFORM_TENANTS_VIEW'),
    (2, 'MANAGE', 'إدارة', 'PLATFORM_TENANT_MANAGE')
) AS v(ord, action_code, action_ar, permission_code)
JOIN SEC_SCREEN_REG s ON s.PAGE_CODE = 'PLATFORM_TENANTS'
ORDER BY v.ord;

INSERT INTO SEC_ROLE_MODULE_GRANT (ROLE_MODULE_GRANT_PK, TENANT_ID, ROLE_ID, MODULE_ID, GRANTED_BY, GRANTED_AT, CREATED_BY, CREATED_AT)
SELECT nextval('SEQ_SEC_ROLE_MODULE_GRANT'), 1, r.ROLE_PK, m.MODULE_REG_PK, 'SYSTEM', CURRENT_TIMESTAMP, 'SYSTEM', CURRENT_TIMESTAMP
FROM SEC_ROLE r JOIN SEC_MODULE_REG m ON m.CODE = 'PLATFORM'
WHERE r.TENANT_ID = 1 AND r.CODE = 'SYS_ADMIN';

INSERT INTO SEC_ROLE_SCREEN_GRANT (ROLE_SCREEN_GRANT_PK, TENANT_ID, ROLE_ID, SCREEN_ID, GRANTED_BY, GRANTED_AT, CREATED_BY, CREATED_AT)
