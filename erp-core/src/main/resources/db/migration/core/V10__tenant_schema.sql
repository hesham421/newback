-- ============================================================
-- V10 — Tenant (row-level multi-tenancy, shared schema) — erp-core step 05
-- Target: POSTGRESQL_16 | after V2..V9
--
-- What this script does:
--   1. CORE_TENANT (global, no TENANT_ID) + its sequence; seeds the PLATFORM tenant (ID 1).
--   2. Every tenant-scoped core table gets TENANT_ID BIGINT NOT NULL (backfilled with 1 = PLATFORM,
--      FK to CORE_TENANT, indexed) and VERSION BIGINT NOT NULL DEFAULT 0 (optimistic locking).
--   3. The three global permission-catalog tables (SEC_MODULE_REG / SEC_SCREEN_REG /
--      SEC_ACTION_REG) get VERSION only — the catalog is code-defined and the same for all tenants.
--   4. The eight SEC tables that had no audit columns get nullable CREATED_BY / CREATED_AT /
--      UPDATED_BY / UPDATED_AT (backfilled from their own lifecycle columns), so every tenant-scoped
--      entity extends AuditableEntity (step 04 report, "Schema conventions check").
--   5. Every UNIQUE constraint on a tenant-scoped table becomes composite with TENANT_ID (the
--      constraint names are kept, so the JPA @UniqueConstraint names stay verbatim).
--   6. Seeds the PLATFORM module / PLATFORM_TENANTS screen / its VIEW + PLATFORM_TENANT_MANAGE actions
--      and grants them to the PLATFORM tenant's SYS_ADMIN role (the bootstrap admin's role).
--
-- Additive-only rule (README.md): everything here is additive EXCEPT two changes the step-05 plan
-- itself sanctions inside this script (recorded in docs/DEVIATIONS.md as plan-sanctioned):
--   (a) ALTER COLUMN TENANT_ID DROP DEFAULT after the backfill, so the application must always
--       supply the tenant (Hibernate @TenantId does);
--   (b) DROP + re-ADD of each unique constraint as its composite (TENANT_ID, ...) form.
-- ============================================================

-- ============================================================
-- 1. CORE_TENANT
-- ============================================================
CREATE SEQUENCE SEQ_CORE_TENANT START WITH 1 INCREMENT BY 1 CACHE 1 NO CYCLE;

CREATE TABLE CORE_TENANT (
  ID           BIGINT        NOT NULL,
  CODE         VARCHAR(32)   NOT NULL,
  NAME_AR      VARCHAR(200)  NOT NULL,
  NAME_EN      VARCHAR(200)  NOT NULL,
  STATUS_CODE  VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
  CREATED_BY   VARCHAR(100)  NOT NULL,
  CREATED_AT   TIMESTAMPTZ   NOT NULL DEFAULT now(),
  UPDATED_BY   VARCHAR(100),
  UPDATED_AT   TIMESTAMPTZ,
  VERSION      BIGINT        NOT NULL DEFAULT 0
);

COMMENT ON TABLE CORE_TENANT IS 'Tenant registry (global — the one core table without TENANT_ID). ID 1 = PLATFORM.';
COMMENT ON COLUMN CORE_TENANT.CODE IS 'Tenant code, ^[A-Z0-9_]{3,32}$, unique; sent by clients as X-Tenant-Code.';
COMMENT ON COLUMN CORE_TENANT.STATUS_CODE IS 'ACTIVE | SUSPENDED — a suspended tenant cannot log in or call any endpoint.';

ALTER TABLE CORE_TENANT ADD CONSTRAINT PK_CORE_TENANT PRIMARY KEY (ID);
ALTER TABLE CORE_TENANT ADD CONSTRAINT UQ_CORE_TENANT_CODE UNIQUE (CODE);
ALTER TABLE CORE_TENANT ADD CONSTRAINT CHK_CORE_TENANT_STATUS CHECK (STATUS_CODE IN ('ACTIVE','SUSPENDED'));
ALTER TABLE CORE_TENANT ADD CONSTRAINT CHK_CORE_TENANT_CODE CHECK (CODE ~ '^[A-Z0-9_]{3,32}$');

-- The PLATFORM tenant: owns every row that existed before this script (the backfill below), the
-- bootstrap admin, and the platform-level operations (/api/v1/platform/**).
INSERT INTO CORE_TENANT (ID, CODE, NAME_AR, NAME_EN, STATUS_CODE, CREATED_BY, CREATED_AT)
VALUES (1, 'PLATFORM', 'المنصة', 'Platform', 'ACTIVE', 'SYSTEM', CURRENT_TIMESTAMP);
