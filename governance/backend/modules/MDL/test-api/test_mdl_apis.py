def setup_grant_mdl_permissions(client: APIClient) -> dict:
    """Not a governed TC — infrastructure precondition setup via SEC's own real, documented
    grant endpoints (API-SEC-014 module grant, API-SEC-016 screen grant, API-SEC-017 action
    grant), required because V19__mdl_security_seed.sql deliberately left SYS_ADMIN without
    the MDL permissions it registered (see its own inline comment). Tolerates
    SEC-409-GRANT-DUP as "already granted" (idempotent across re-runs).

    # erp-core 1.2.0: SYS_ADMIN already holds the MDL grants (V7__sec_seed.sql, ex-V21) and is a
    # super role — docs/steps/04-report.md, docs/steps/06-report.md. Every grant below is
    # expected to answer SEC-409-GRANT-DUP; the suite stays as an idempotent precondition check."""
    start_suite("0. Setup — grant MDL permissions to SYS_ADMIN role")
    ctx: dict = {"granted": False, "newly_granted_module": False}

    def _find_role():
        r = client.post("/api/v1/sec/roles/search", {"page": 0, "size": 200})
        if r.status_code != 200:
            return False, f"HTTP {r.status_code} searching roles", snippet(r)
        content = extract_list(r, "content") or []
        match = next((row for row in content if row.get("code") == "SYS_ADMIN"), None)
        if not match:
            return False, "no role with code=SYS_ADMIN found", snippet(r)
        ctx["role_id"] = match.get("rolePk")
        return True, f"SYS_ADMIN rolePk={ctx['role_id']}", snippet(r)
    if not run("locate SYS_ADMIN role", _find_role).passed:
        return ctx

    def _find_registry():
        r = client.post("/api/v1/sec/registry/search", {"page": 0, "size": 200})
        if r.status_code != 200:
            return False, f"HTTP {r.status_code} searching registry", snippet(r)
        content = extract_list(r, "content") or []
        mdl = next((row for row in content if row.get("code") == "MDL"), None)
        if not mdl:
            return False, "no module with code=MDL found in registry", snippet(r)
        ctx["module_id"] = mdl.get("moduleRegPk")
        screen_ids = {}
        action_ids = {}
        for screen in mdl.get("screens", []):
            screen_ids[screen.get("pageCode")] = screen.get("screenRegPk")
            for action in screen.get("actions", []):
                action_ids[action.get("permissionCode")] = action.get("actionRegPk")
        ctx["screen_ids"] = screen_ids
        ctx["action_ids"] = action_ids
        needed_actions = {"PERM_MDL_LOOKUPS_VIEW", "PERM_MDL_LOOKUPS_CREATE",
                           "PERM_MDL_LOOKUPS_UPDATE", "PERM_MDL_TYPE_REGISTRY_VIEW"}
        missing = needed_actions - action_ids.keys()
        if missing:
            return False, f"registry missing action rows: {missing}", snippet(r)
        return True, (f"module_id={ctx['module_id']}, screens={screen_ids}, "
                       f"actions={list(action_ids.keys())}"), snippet(r)
    if not run("locate MDL module/screens/actions in SEC registry", _find_registry).passed:
        return ctx

    role_id = ctx["role_id"]
    module_id = ctx["module_id"]

    def _grant_module():
        r = client.post(f"/api/v1/sec/roles/{role_id}/modules", {"moduleId": module_id})
        if r.status_code in (200, 201):
            ctx["newly_granted_module"] = True
            return True, f"HTTP {r.status_code} (newly granted)", snippet(r)
        if r.status_code == 409 and extract_error_code(r) == "SEC-409-GRANT-DUP":
            return True, "HTTP 409 SEC-409-GRANT-DUP (already granted)", snippet(r)
        return False, f"HTTP {r.status_code}, error.code={extract_error_code(r)}", snippet(r)
    if not run("grant MDL module to SYS_ADMIN", _grant_module).passed:
        return ctx

    for page_code in ("MDL_LOOKUPS", "MDL_TYPE_REGISTRY"):
        screen_id = ctx["screen_ids"].get(page_code)

        def _grant_screen(sid=screen_id, pc=page_code):
            r = client.post(f"/api/v1/sec/roles/{role_id}/screens", {"screenId": sid})
            if r.status_code in (200, 201):
                return True, f"HTTP {r.status_code} (newly granted, {pc})", snippet(r)
            if r.status_code == 409 and extract_error_code(r) == "SEC-409-GRANT-DUP":
                return True, f"HTTP 409 SEC-409-GRANT-DUP (already granted, {pc})", snippet(r)
            return False, f"HTTP {r.status_code}, error.code={extract_error_code(r)}", snippet(r)
        if not run(f"grant screen {page_code} to SYS_ADMIN", _grant_screen).passed:
            return ctx

    for perm_code in ("PERM_MDL_LOOKUPS_VIEW", "PERM_MDL_LOOKUPS_CREATE",
                      "PERM_MDL_LOOKUPS_UPDATE", "PERM_MDL_TYPE_REGISTRY_VIEW"):
        action_id = ctx["action_ids"].get(perm_code)

        def _grant_action(aid=action_id, pc=perm_code):
            r = client.post(f"/api/v1/sec/roles/{role_id}/actions", {"actionId": aid})
            if r.status_code in (200, 201):
                return True, f"HTTP {r.status_code} (newly granted, {pc})", snippet(r)
            if r.status_code == 409 and extract_error_code(r) == "SEC-409-GRANT-DUP":
                return True, f"HTTP 409 SEC-409-GRANT-DUP (already granted, {pc})", snippet(r)
            return False, f"HTTP {r.status_code}, error.code={extract_error_code(r)}", snippet(r)
        if not run(f"grant action {perm_code} to SYS_ADMIN", _grant_action).passed:
            return ctx

    ctx["granted"] = True
    return ctx


