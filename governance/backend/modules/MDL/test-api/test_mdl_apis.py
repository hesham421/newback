def report_markdown() -> str:
    lines = ["# MDL api-verify problems report", "", f"Run: {RUN_ID}  ·  Tier: FULL", ""]
    total_pass = sum(s.passed_count for s in SUITES)
    total_fail = sum(s.failed_count for s in SUITES)
    lines.append(f"**Totals: {total_pass} PASS / {total_fail} FAIL** (observations excluded)")
    lines.append("")
    lines.append("## Suites")
    for s in SUITES:
        lines.append(f"### {s.entity} — {s.passed_count} pass / {s.failed_count} fail")
        for r in s.results:
            mark = "PASS" if r.passed else "FAIL"
            lines.append(f"- [{mark}] {r.name} — {r.detail}")
    lines.append("")
    lines.append("## Observations (Stage E, never pass/fail)")
    for o in OBSERVATIONS:
        lines.append(f"- {o.name} — {o.detail}")
    lines.append("")
    lines.append("## Problems (bucketed)")
    likely_bug, mismatch, infra = [], [], []
    for s in SUITES:
        for r in s.results:
            if r.passed:
                continue
            entry = f"{s.entity} :: {r.name} — {r.detail}"
            if "EXCEPTION" in r.detail and ("Connection" in r.detail or "Timeout" in r.detail):
                infra.append(entry)
            else:
                likely_bug.append(entry)
    lines.append("### Likely real bug")
    lines.extend(f"- {x}" for x in likely_bug) if likely_bug else lines.append("- none")
    lines.append("### Test assumption mismatch")
    lines.append("- TC-MDL-010: manifest text says \"sortOrder persisted as 3,1,2\"; actual "
                 "implementation (LookupValueService#reorder) assigns 0-based list position — "
                 "not asserted literally, the behavioral read-order check is asserted instead.")
    lines.append("- TC-MDL-004/009 step 2: manifest text says the deactivated/excluded value(s) "
                 "\"no longer returned\" / \"returns no values\"; for a deactivated TYPE this "
                 "surfaces as 404 MDL-404-TYPE-KEY (same path as an unknown key), not a 200 "
                 "empty array — asserted against the actual source-confirmed behavior.")
    lines.append("### Infrastructure")
    lines.extend(f"- {x}" for x in infra) if infra else lines.append("- none")
    lines.append("")
    lines.append("## TC-MDL-014 (INT-XM) — not exercised, documented reason")
    lines.append(
        "XM-MDL-001 (MDL -> SEC module-registry check) is implemented as a direct in-process "
        "Spring bean injection (`SecModuleRegistryApi`), confirmed in "
        "`LookupTypeService` — not a network call. There is no HTTP-level way for this script "
        "to make 'SEC unreachable' true; that would require a unit/integration test that mocks "
        "the injected bean, which is outside api-verify's real-HTTP-only scope. This matches "
        "the pre-existing `api_doc_gaps[]` entry in execution-state.json recorded during the "
        "DOC/INT-C phases. TC-MDL-014 is reported as a GAP, not a fabricated PASS."
    )
    return "\n".join(lines)


def _write_run_report() -> None:
    # erp-core 1.2.0 adaptation: the auto-generated run report no longer overwrites the curated
    # mdl_problems_report.md (which now holds the 1.2.0 classification); it is written only when
    # env MDL_RUN_REPORT names a path. — legacy-test brief, step 5
    path = os.environ.get("MDL_RUN_REPORT")
    if not path:
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(report_markdown())
    print(f"Run report written to {path}")


def main() -> int:
    print(f"MDL api-verify run — RUN_ID={RUN_ID}, tier=FULL, base={BASE_URL}, tenant={TENANT_CODE}")
    client = APIClient()

    if not ADMIN_PASSWORD:
        print("FATAL: env ERP_BOOTSTRAP_ADMIN_PASSWORD is not set (the bootstrap admin password) — aborting.")
        return 2
    token = client.login(ADMIN_USERNAME, ADMIN_PASSWORD)
    if not token:
        print(f"FATAL: could not log in as {ADMIN_USERNAME} (tenant {TENANT_CODE}) — aborting.")
        return 2
    client.token = token
    print(f"Logged in as {ADMIN_USERNAME}.")

    grant_ctx = setup_grant_mdl_permissions(client)
    if not grant_ctx.get("granted"):
        print("FATAL: could not establish MDL permissions for the admin caller — every "
              "subsequent MDL call would 403. Aborting without exercising any MDL entity.")
        _write_run_report()
        return 2

    try:
        type_ctx = test_lookup_type(client)
        test_lookup_value(client, type_ctx)
    finally:
        cleanup(client, grant_ctx)

    total_pass = sum(s.passed_count for s in SUITES)
    total_fail = sum(s.failed_count for s in SUITES)
    print(f"\n=== SUMMARY: {total_pass} PASS / {total_fail} FAIL / {len(OBSERVATIONS)} observations ===")
    _write_run_report()

    return 0 if total_fail == 0 else 1


