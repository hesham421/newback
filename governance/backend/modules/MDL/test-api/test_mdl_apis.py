def cleanup(client: APIClient, grant_ctx: dict):
    """Stage F teardown — reverse of the manifest's DEPENDENCY ORDER (LookupType, then
    LookupValue) means cleanup order is LookupValue first, then LookupType. Both entities
    have a real deactivate (soft) endpoint per the ENTITY CRUD CHECKLIST — no hard delete
    used, matching api-verify-config.md's DELETE=soft convention.

    Also reverses the setup-phase permission grant (see module docstring) IF this run is
    the one that newly created it — never touches a grant that already existed before this
    run started, so a concurrent session's own setup is left alone.
    """
    print("\n=== CLEANUP (reverse dependency order) ===")

    for value_id in created_ids["LookupValue"]:
        try:
            r = client.delete(f"/api/v1/mdl/lookup-values/{value_id}")
            print(f"  deactivate LookupValue {value_id}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  deactivate LookupValue {value_id} FAILED: {e}")

    for type_id in created_ids["LookupType"]:
        try:
            r = client.delete(f"/api/v1/mdl/lookup-types/{type_id}")
            print(f"  deactivate LookupType {type_id}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  deactivate LookupType {type_id} FAILED: {e}")

    if grant_ctx.get("newly_granted_module") and grant_ctx.get("role_id") and grant_ctx.get("module_id"):
        try:
            r = client.delete(f"/api/v1/sec/roles/{grant_ctx['role_id']}/modules/{grant_ctx['module_id']}")
            print(f"  revoke temporary MDL module grant from SYS_ADMIN: {r.status_code} "
                  "(cascades the 2 screen + 4 action grants this run added)")
        except Exception as e:  # noqa: BLE001
            print(f"  revoke temporary MDL module grant FAILED: {e}")
    elif grant_ctx.get("granted"):
        LEFT_BEHIND_NOTES.append(
            "MDL module/screen/action grant on SYS_ADMIN already existed before this run "
            "(not newly created by it) — left in place, not revoked."
        )

    if LEFT_BEHIND_NOTES:
        print("\n  Notes:")
        for note in LEFT_BEHIND_NOTES:
            print(f"    - {note}")


