    run("create LookupType fixture: deactivation test (TC-MDL-004 setup)", _create_fixture(key_deact, "deact_id"))
    run("create LookupType fixture: payment method (TC-MDL-011 setup)", _create_fixture(key_payment, "payment_id"))
    run("create LookupType fixture: reorder (TC-MDL-010 setup)", _create_fixture(key_reorder, "reorder_id"))
    run("create LookupType fixture: search (TC-MDL-005 setup)", _create_fixture(key_search, "search_id"))
    # Dedicated second-owner fixture for TC-MDL-013 — SEC is a real, distinct, registered
    # module (unlike the former "FIN" fixture value), so this genuinely exercises a second
    # owner group, not a self-registration.
