def cleanup(c: APIClient):
    """Reverse of the manifest's DEPENDENCY ORDER (FileDocument, then FileCategory).
    FILE documents NO hard delete for either entity — DELETE /files/{id} sets
    fileStatusId=DELETED and explicitly RETAINS the bytes (RULE-FILE-006), and
    DELETE /files/categories/{id} only clears the active flag. Every row below
    therefore survives and is listed individually, never summarised as 'cleaned up'."""
    print("\n=== CLEANUP (reverse dependency order) ===")

    doc_ids = [i for i in created["FileDocument"] if i]
    for fid in doc_ids:
        try:
            # DELETED is terminal (FileDocumentDomain): re-deleting an already-deleted
            # row is a legitimate 422, not a cleanup failure — skip it instead.
            cur = field_of(c.get(f"/api/v1/files/{fid}"), "fileStatusId")
            if cur == "DELETED":
                print(f"  FileDocument {fid}: already DELETED — skipped")
                continue
            r = c.delete(f"/api/v1/files/{fid}", params={"action": "DELETE"})
            print(f"  soft-delete FileDocument {fid}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  soft-delete FileDocument {fid} FAILED: {e}")
    if doc_ids:
        # erp-core 1.2.0: content lives in the configured storage provider (DB by default;
        # FILE_CONTENT is nullable and filled for DB only) — P2/db-script.md "Implementation
        # Addendum — erp-core 1.2.0"; DEVIATIONS [07].
        LEFT_BEHIND.append(
            f"FILE_DOCUMENT rows {doc_ids} — set to fileStatusId=DELETED (soft). FILE "
            f"documents no hard delete, and RULE-FILE-006 RETAINS the bytes; with the default "
            f"DB storage provider the BYTEA FILE_CONTENT column of each of these rows still "
            f"holds this run's uploaded payload (~{UNDER_LIMIT_BYTES // 1024} KB for the "
            f"largest; with LOCAL/S3 the object stays in that store). Purge SQL: "
            f"DELETE FROM FILE_DOCUMENT WHERE ID IN ({', '.join(str(i) for i in doc_ids)});")

    cat_ids = [i for i in created["FileCategory"] if i]
    for cid in cat_ids:
        try:
            r = c.delete(f"/api/v1/files/categories/{cid}")
            print(f"  deactivate FileCategory {cid}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  deactivate FileCategory {cid} FAILED: {e}")
    if cat_ids:
        LEFT_BEHIND.append(
            f"FILE_CATEGORY rows {cat_ids} (codes CONTRACTS_{RUN_ID}, IMAGES_{RUN_ID}, "
            f"RETIRED_{RUN_ID}) — deactivated (soft); FILE documents no hard delete and no "
            f"activate endpoint. Purge SQL: DELETE FROM FILE_CATEGORY WHERE ID IN "
            f"({', '.join(str(i) for i in cat_ids)});")

    # erp-core 1.2.0: TC-BE-FILE-019's no-role staff user (SEC exposes deactivate, not delete).
    user_ids = [i for i in created["SecUser"] if i]
    for uid in user_ids:
        try:
            r = c.delete(f"/api/v1/sec/users/{uid}")
            print(f"  deactivate SecUser {uid}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  deactivate SecUser {uid} FAILED: {e}")
    if user_ids:
        LEFT_BEHIND.append(
            f"SEC_USER rows {user_ids} (username file-noperm-{RUN_ID}, tenant PLATFORM, no role) "
            f"— deactivated; SEC exposes no hard delete for users.")

    # FILE writes into no registry or reference table another module's rules read: both of
    # its tables are module-local, and its two LOVs are read from MDL, never written to.
    # Nothing qualifies as permanent residue under stage F.


