class APIClient:
    def __init__(self, base_url: str = BASE_URL):
        self.base_url = base_url
        self.token: Optional[str] = None
        self.session = requests.Session()

    def _headers(self, token: Optional[str] = None, lang: Optional[str] = None,
                 json_body: bool = True) -> dict:
        h = {"Content-Type": "application/json"} if json_body else {}
        tok = token if token is not None else self.token
        if tok:
            h["Authorization"] = f"Bearer {tok}"
        if lang:
            h["Accept-Language"] = lang
        return h

    def _make(self, method, path, json_body=None, params=None, token=None,
              lang=None, timeout=60):
        return self.session.request(
            method, f"{self.base_url}{path}", json=json_body, params=params,
            headers=self._headers(token, lang), timeout=timeout,
        )

    def get(self, path, params=None, token=None, lang=None):
        return self._make("GET", path, params=params, token=token, lang=lang)

    def post(self, path, json_body=None, token=None, lang=None):
        return self._make("POST", path, json_body=json_body, token=token, lang=lang)

    def put(self, path, json_body=None, token=None, lang=None):
        return self._make("PUT", path, json_body=json_body, token=token, lang=lang)

    def delete(self, path, params=None, token=None):
        return self._make("DELETE", path, params=params, token=token)

    def upload(self, content: bytes, file_name: str, form: dict,
               token: Optional[str] = None, omit_auth: bool = False):
        """POST /api/v1/files — multipart/form-data.

        Part names come from the implementation contract the api-docs describe:
        `file` (the binary part) plus the UploadRequest fields. The docs render the
        metadata as a nested `request` object; the controller binds it with
        @ModelAttribute, i.e. FLAT form fields. Both spellings are exercised — the
        flat one asserted, the documented nested one recorded as an observation.
        """
        files = {"file": (file_name, content, "application/octet-stream")}
        data = {k: str(v) for k, v in form.items() if v is not None}
        headers = {} if omit_auth else self._headers(token, json_body=False)
        return self.session.post(f"{self.base_url}/api/v1/files",
                                 files=files, data=data, headers=headers, timeout=120)

    def download(self, token_value: str, token: Optional[str] = None):
        """GET /api/v1/files/download?token= — raw byte stream, no envelope."""
        return self.session.get(f"{self.base_url}/api/v1/files/download",
                                params={"token": token_value},
                                headers=self._headers(token, json_body=False), timeout=60)

    def login(self, username: str, password: str,
              tenant_code: str = TENANT_CODE) -> Optional[str]:
        # erp-core 1.2.0: login must carry X-Tenant-Code (TenantResolutionFilter) — DEVIATIONS [05].
        # The token's `tid` claim then carries the tenant, so no other call needs the header.
        r = self.session.post(f"{self.base_url}/api/v1/sec/auth/login",
                              json={"username": username, "password": password},
                              headers={"Content-Type": "application/json",
                                       "X-Tenant-Code": tenant_code},
                              timeout=60)
        if r.status_code == 200:
            return ((r.json().get("data")) or {}).get("accessToken")
        return None


def data_of(resp) -> Any:
    try:
        return resp.json().get("data")
    except Exception:  # noqa: BLE001
        return None


def field_of(resp, key) -> Any:
    d = data_of(resp)
    return d.get(key) if isinstance(d, dict) else None


def err_code(resp) -> Optional[str]:
    try:
        return (resp.json().get("error") or {}).get("code")
    except Exception:  # noqa: BLE001
        return None


def snippet(resp, limit: int = 300) -> str:
    ctype = resp.headers.get("Content-Type", "")
    if "json" not in ctype:
        return f"<{len(resp.content)} bytes, Content-Type={ctype}>"
    try:
        return json.dumps(resp.json(), ensure_ascii=False)[:limit]
    except Exception:  # noqa: BLE001
        return (resp.text or "")[:limit]


def expect_status(resp, want: int, what: str):
    return (resp.status_code == want,
            f"{what}: HTTP {resp.status_code} (want {want})", snippet(resp))


def expect_error(resp, want_status: int, want_code: str, what: str):
    got = err_code(resp)
    ok = resp.status_code == want_status and got == want_code
    return (ok,
            f"{what}: HTTP {resp.status_code}/{got} (want {want_status}/{want_code})",
            snippet(resp))


def field_errors(resp) -> list:
    """The `error.fieldErrors` array of the platform validation envelope (may be absent/null)."""
    try:
        return (resp.json().get("error") or {}).get("fieldErrors") or []
    except Exception:  # noqa: BLE001
        return []


def expect_validation_field(resp, want_field: str, what: str):
    """Assert the platform's deliberate bean-validation refusal: HTTP 400, wire code
    `VALIDATION_ERROR`, and a `fieldErrors` entry naming `want_field`.

    This is GlobalExceptionHandler.handleValidation's documented shape. Asserting the field
    name (not just the status) is what keeps such a test meaningful: it still proves the rule
    is enforced AND on which field, which the generic per-module business code cannot express
    because it carries no per-field detail and reports only one failure at a time.
    """
    got = err_code(resp)
    fields = [fe.get("field") for fe in field_errors(resp)]
    ok = (resp.status_code == 400
          and got == "VALIDATION_ERROR"
          and want_field in fields)
    return (ok,
            f"{what}: HTTP {resp.status_code}/{got}, fieldErrors={fields} "
            f"(want 400/VALIDATION_ERROR naming '{want_field}')",
            snippet(resp))


