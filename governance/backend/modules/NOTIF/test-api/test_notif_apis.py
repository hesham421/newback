def main() -> int:
    global BASE_URL
    if len(sys.argv) > 1:
        BASE_URL = sys.argv[1].rstrip("/")
    if not ADMIN_PASSWORD:
        print("FATAL: set ERP_BOOTSTRAP_ADMIN_PASSWORD (the bootstrap admin's password) — "
              "ENVIRONMENT_FAILURE", file=sys.stderr)
        return 2

    c = APIClient(BASE_URL)
    print(f"api-verify — NOTIF · legacy suite adapted to erp-core 1.2.0 · RUN_ID={RUN_ID} · "
          f"target {BASE_URL} · tenant {TENANT_CODE}")

    tok = c.login(ADMIN_USERNAME, ADMIN_PASSWORD)
    if not tok:
        print("FATAL: could not authenticate — ENVIRONMENT_FAILURE", file=sys.stderr)
        return 2
    c.token = tok
    # erp-core 1.2.0: the JWT carries the caller's SEC_USER id as `uid` (with `tid`, `realm`) —
    # DEVIATIONS [05], [06]; used to pick the caller as the IN_APP recipient (see preflight).
    ctx["caller_user_id"] = jwt_claim(tok, "uid")

    try:
        grants(c)
        preflight(c)
        test_template(c)      # DEPENDENCY ORDER 1
        test_channel(c)       # DEPENDENCY ORDER 2
        test_dispatch(c)      # DEPENDENCY ORDER 3 (creates NOTIF_LOG via fan-out)
        test_logs(c)
        test_lookups(c)
        test_authorization(c)
    finally:
        try:
            cleanup(c)
        except Exception as e:  # noqa: BLE001
            print(f"cleanup FAILED: {e}")
        # erp-core 1.2.0: the per-run report is opt-in (NOTIF_RUN_REPORT) so a run never
        # overwrites the maintained notif_problems_report.md.
        if os.environ.get("NOTIF_RUN_REPORT"):
            write_report(os.environ["NOTIF_RUN_REPORT"])

    total_f = sum(s.failed_count for s in SUITES)
    print(f"\nTOTAL: {sum(s.passed_count for s in SUITES)} passed, {total_f} failed")
    return 1 if total_f else 0


if __name__ == "__main__":
    raise SystemExit(main())
