        """TC-BE-NOTIF-004 / TC-BE-NOTIF-015 — flipping isEnabledFl changes the dispatch outcome."""
        cid = ctx.get("channel_id")
        if not cid:
            return False, "BLOCKED: no channel config owned by this run", ""
        d = c.delete(f"/api/v1/notifications/channels/{cid}")      # documented "disable"
        if d.status_code != 204:
            return False, f"disable endpoint returned HTTP {d.status_code}", snippet(d)
        ctx["channel_disabled"] = True
        r = c.post("/api/v1/notifications/dispatch",
                   dict(base, channelHint=[CHANNEL_TYPE_ENABLED]))
        ids = (data_of(r) or {}).get("logIds") or []
        created["NotificationLog"].extend(ids)
        if not ids:
            return False, f"HTTP {r.status_code}, no logIds returned", snippet(r)
        # CHANNEL_DISABLED is decided synchronously at dispatch and is final, so it is read at
        # once (no polling) — that also proves the row was never QUEUED.
        g = c.get(f"/api/v1/notifications/logs/{ids[0]}")
        status = field_of(g, "notificationStatusId")
        retry = field_of(g, "retryCount")
        # erp-core 1.2.0: + `attempts` (V13) — a CHANNEL_DISABLED row is never queued, so 0
